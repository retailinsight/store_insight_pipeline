-- Cornelious (13 Sep): CRT KPI panel served an older row (RUN_DATE 2026-09-10,
-- ANALYSIS_DATE 2026-09-09, old "performance_breakdown" narrative) after the
-- PR #79 KPI SP went live. Root cause of the ambiguity: KPI_AVAILABILITY_SUMMARY
-- can hold more than one RUN_DATE for the same STORE_ID + ANALYSIS_DATE
-- (re-runs, manual DEV runs), so any consumer that filters on ANALYSIS_DATE
-- alone - or on MAX(RUN_DATE) computed elsewhere - can pick a stale row.
--
-- Fix: KPI_AVAILABILITY_LATEST_V1 = one row per STORE_ID + ANALYSIS_DATE, the
-- newest RUN_DATE wins. IS_LATEST_FOR_STORE marks each store's newest analysis
-- date. The CRT API should read this view, not the base table. Deployed live
-- in PROD and DEV on 13 Sep 2026 (the DEV table is re-cloned from PROD daily at
-- 07:00 by CLONE_PROD_TO_DEV_SP; views bind by name so they survive the clone).

USE ROLE STORE_INSIGHT_ROLE;
USE WAREHOUSE STORE_INSIGHT_WH;

-- Prod
CREATE OR REPLACE VIEW STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_LATEST_V1
COMMENT = 'One KPI row per STORE_ID + ANALYSIS_DATE: the most recent RUN_DATE wins. IS_LATEST_FOR_STORE=TRUE marks the newest ANALYSIS_DATE per store. Consumers (CRT API) should read this instead of the base table so re-runs for the same analysis date never surface stale rows.'
AS
SELECT *,
       ROW_NUMBER() OVER (PARTITION BY STORE_ID ORDER BY ANALYSIS_DATE DESC, RUN_DATE DESC) = 1 AS IS_LATEST_FOR_STORE
FROM STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_SUMMARY
QUALIFY ROW_NUMBER() OVER (PARTITION BY STORE_ID, ANALYSIS_DATE ORDER BY RUN_DATE DESC) = 1;

GRANT SELECT ON VIEW STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_LATEST_V1 TO ROLE STOREINSIGHT;
GRANT SELECT ON VIEW STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_LATEST_V1 TO ROLE STORE_INSIGHT_ROLE;

-- Dev
CREATE OR REPLACE VIEW STORE_INSIGHT_DEV.PUBLIC.KPI_AVAILABILITY_LATEST_V1
COMMENT = 'One KPI row per STORE_ID + ANALYSIS_DATE: the most recent RUN_DATE wins. IS_LATEST_FOR_STORE=TRUE marks the newest ANALYSIS_DATE per store. Consumers (CRT API) should read this instead of the base table so re-runs for the same analysis date never surface stale rows.'
AS
SELECT *,
       ROW_NUMBER() OVER (PARTITION BY STORE_ID ORDER BY ANALYSIS_DATE DESC, RUN_DATE DESC) = 1 AS IS_LATEST_FOR_STORE
FROM STORE_INSIGHT_DEV.PUBLIC.KPI_AVAILABILITY_SUMMARY
QUALIFY ROW_NUMBER() OVER (PARTITION BY STORE_ID, ANALYSIS_DATE ORDER BY RUN_DATE DESC) = 1;

GRANT SELECT ON VIEW STORE_INSIGHT_DEV.PUBLIC.KPI_AVAILABILITY_LATEST_V1 TO ROLE STOREINSIGHT;
GRANT SELECT ON VIEW STORE_INSIGHT_DEV.PUBLIC.KPI_AVAILABILITY_LATEST_V1 TO ROLE STORE_INSIGHT_ROLE;

-- Verify: one row per store+analysis date, 121/122 stores flagged latest
SELECT 'PROD' AS env, COUNT(*) AS rows_, COUNT(DISTINCT STORE_ID || ANALYSIS_DATE) AS uniq, COUNT_IF(IS_LATEST_FOR_STORE) AS latest_stores, MAX(RUN_DATE) AS max_run
FROM STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_LATEST_V1;
SELECT 'DEV' AS env, COUNT(*) AS rows_, COUNT(DISTINCT STORE_ID || ANALYSIS_DATE) AS uniq, COUNT_IF(IS_LATEST_FOR_STORE) AS latest_stores, MAX(RUN_DATE) AS max_run
FROM STORE_INSIGHT_DEV.PUBLIC.KPI_AVAILABILITY_LATEST_V1;

-- What CRT should show for store 204 today (newest analysis date, newest run)
SELECT STORE_ID, RUN_DATE, ANALYSIS_DATE, TW_OSA_PCT, LW_OSA_PCT, MISSION_OSA_PCT,
       PARSE_JSON(OVERALL_DETAILS_JSON):summary::STRING AS summary
FROM STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_LATEST_V1
WHERE STORE_ID = 204 AND IS_LATEST_FOR_STORE;
