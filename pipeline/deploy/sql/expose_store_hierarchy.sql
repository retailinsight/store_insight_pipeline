-- Expose store names to the app (Cornelious, 27 Aug):
-- STORE_HIERARCHY_V1 (STORE_ID, STORE_NAME, REGION, AREA_NUMBER) already
-- exists in prod, fed daily at ~11:00 by TASK_LOAD_WMD_STORE_HIERARCHY.
-- 1. Grant the app role read access in prod.
-- 2. Mirror it into dev as a view over prod (read-only reference data).

USE ROLE STORE_INSIGHT_ROLE;
USE WAREHOUSE STORE_INSIGHT_WH;

-- 1. Prod: app role read access
GRANT SELECT ON VIEW STORE_INSIGHT_DB.PUBLIC.STORE_HIERARCHY_V1 TO ROLE STOREINSIGHT;

-- 2. Dev: same name, same shape, sourced from prod (no daily clone needed)
CREATE OR REPLACE VIEW STORE_INSIGHT_DEV.PUBLIC.STORE_HIERARCHY_V1 AS
SELECT STORE_ID, STORE_NAME, REGION, AREA_NUMBER
FROM STORE_INSIGHT_DB.PUBLIC.STORE_HIERARCHY_V1;

GRANT SELECT ON VIEW STORE_INSIGHT_DEV.PUBLIC.STORE_HIERARCHY_V1 TO ROLE STOREINSIGHT;
GRANT SELECT ON VIEW STORE_INSIGHT_DEV.PUBLIC.STORE_HIERARCHY_V1 TO ROLE STORE_INSIGHT_ROLE;

-- Verify
SELECT 'DEV' AS env, COUNT(*) AS stores FROM STORE_INSIGHT_DEV.PUBLIC.STORE_HIERARCHY_V1;
SELECT STORE_ID, STORE_NAME FROM STORE_INSIGHT_DEV.PUBLIC.STORE_HIERARCHY_V1 ORDER BY STORE_ID LIMIT 3;
