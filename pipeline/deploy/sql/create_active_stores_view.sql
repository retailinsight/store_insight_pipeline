-- Imran (25 Aug): stores 207 (Old Road) and 211 (Coggeshall) show empty in the app.
-- Cause: the alert pipeline covers ~122 stores; STORE_HIERARCHY_V1 has the full
-- 174-store estate. Any store list built from the hierarchy (or test accounts)
-- includes ~52 stores with no data. 207's last alerts were 2026-07-15; 211 never
-- had any. Fix: ACTIVE_STORES_V1 = stores with data on the latest run date,
-- with real names - the correct source for the app's store list.

USE ROLE STORE_INSIGHT_ROLE;
USE WAREHOUSE STORE_INSIGHT_WH;

-- Prod
CREATE OR REPLACE VIEW STORE_INSIGHT_DB.PUBLIC.ACTIVE_STORES_V1 AS
WITH latest_alerts AS (
    SELECT MAX(RUN_DATE) AS d FROM STORE_INSIGHT_DB.PUBLIC.ALERTS_PIPELINE
),
latest_kpi AS (
    SELECT MAX(RUN_DATE) AS d FROM STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_SUMMARY
),
active AS (
    SELECT DISTINCT STORE_ID FROM STORE_INSIGHT_DB.PUBLIC.ALERTS_PIPELINE, latest_alerts
    WHERE RUN_DATE = latest_alerts.d
    UNION
    SELECT DISTINCT STORE_ID FROM STORE_INSIGHT_DB.PUBLIC.KPI_AVAILABILITY_SUMMARY, latest_kpi
    WHERE RUN_DATE = latest_kpi.d
)
SELECT a.STORE_ID,
       COALESCE(h.STORE_NAME, 'Store ' || a.STORE_ID) AS STORE_NAME,
       h.REGION,
       h.AREA_NUMBER
FROM active a
LEFT JOIN STORE_INSIGHT_DB.PUBLIC.STORE_HIERARCHY_V1 h ON h.STORE_ID = a.STORE_ID;

GRANT SELECT ON VIEW STORE_INSIGHT_DB.PUBLIC.ACTIVE_STORES_V1 TO ROLE STOREINSIGHT;

