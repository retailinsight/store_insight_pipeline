"""Regenerate Cluster Dashboard store fixtures from a metrics pull.

Reads scripts/out/cluster_store_metrics_*.json and emits, deterministically:
  - store-insight-ui/src/data/clusterOpenActionsFixture.ts  (full open-action lists)
  - store-insight-ui/src/data/clusterStoreFixture.ts        (table rows + Panel D details)
  - optionally splices the STORES array + CLUSTER consts into the standalone HTML
    (--html flag; index-based splice, never regex over nested arrays)

Trend groups (Groups 1-3 tiles + panels) are NOT generated here — candidate
selection and panel copy are review steps (see
.devin/skills/cluster-dashboard-refresh/SKILL.md). Group 3 gap rows come from
build_panel_payload.py.

Usage:
    python regen_cluster_fixtures.py [--metrics PATH] [--html PATH]
Defaults: newest out/cluster_store_metrics_*.json; UI at
    ../../store-insight-ui relative to this repo's parent directory.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
REPO_DIR = SCRIPTS_DIR.parent
UI_DATA = REPO_DIR.parent / "store-insight-ui" / "src" / "data"

CHIP = {
    "OSA_STORE_ACTIONABLE": "OSA actionable",
    "OSA_BIG_DROP": "OSA drop",
    "OSA_RECURRING_SLOT": "OSA recurring",
    "COMPLIANCE": "Compliance",
    "BINNED_WASTE": "Binned waste",
    "PROMPTED_MARKDOWN_COMPLIANCE": "Markdown",
}
ACTIONED_STATES = {"completed", "partial", "couldnt_complete", "in_progress", "reminder_set"}


def latest_metrics(out_dir: Path) -> Path:
    files = sorted(out_dir.glob("cluster_store_metrics_*.json"))
    if not files:
        sys.exit(f"no cluster_store_metrics_*.json in {out_dir} — run pull_cluster_store_metrics.py first")
    return files[-1]


def s(v) -> str:
    """JSON-escape a string for embedding in TS/JS source."""
    return json.dumps(str(v), ensure_ascii=False)


def fmt_sent(iso: str) -> str:
    d = date.fromisoformat(iso[:10])
    return f"{d.day} {d.strftime('%b')} {d.year}"


def title(name: str) -> str:
    return name.strip().title() if name else ""


def open_items(d: dict) -> dict[str, list[dict]]:
    """Unresolved sent alerts per pilot store, newest first."""
    pilots = set(d["pilot_store_ids"])
    items: dict[str, list[dict]] = {str(sid): [] for sid in pilots}
    for r in d["all_open"]:
        if r["store_id"] not in pilots:
            continue
        items[str(r["store_id"])].append(r)
    for rows in items.values():
        rows.sort(key=lambda r: r["sent_date"], reverse=True)
    return items


def depts_of(kpi: dict) -> list[tuple[str, float]]:
    """Division-level OSCA rows, worst first."""
    try:
        od = json.loads(kpi.get("osca_details_json") or "{}")
    except json.JSONDecodeError:
        return []
    rows = []
    for dv in od.get("performance_breakdown", {}).get("by_division", []):
        try:
            rows.append((title(dv["division"]), float(str(dv["osca"]).rstrip("%"))))
        except (KeyError, TypeError, ValueError):
            continue
    rows.sort(key=lambda x: x[1])
    return rows


def pilots_by_name(d: dict) -> list[int]:
    return sorted(d["pilot_store_ids"], key=lambda s: d["store_names"].get(str(s), str(s)))


def stats_of(d: dict, sid: int) -> dict:
    st = d["action_stats"].get(str(sid), {})
    sent = st.get("sent", 0)
    actioned = sum(st.get(k, 0) for k in ACTIONED_STATES)
    return {
        "sent": sent,
        "actioned": actioned,
        "completed": st.get("completed", 0),
        "partial": st.get("partial", 0),
        "compliance": f"{actioned / sent * 100:.1f}%" if sent else "—",
    }


def cluster_avgs(d: dict) -> dict:
    pilots = d["pilot_store_ids"]
    kpis = [d["kpi_latest"][str(s)] for s in pilots if str(s) in d["kpi_latest"]]
    osa = sum(float(k["tw_osa_pct"]) for k in kpis) / len(kpis)
    prompted = sum(float(k["prompted_markdown_pct"]) for k in kpis) / len(kpis)
    wq = sum(float(d["waste"].get(str(s), {}).get("waste_qty") or 0) for s in pilots)
    mq = sum(float(d["waste"].get(str(s), {}).get("md_qty") or 0) for s in pilots)
    return {
        "osa": f"{osa:.1f}%",
        "prompted": f"{prompted:.1f}%",
        "waste": f"{wq / mq * 100:.1f}%" if mq else "—",
    }


def emit_open_actions(d: dict, items: dict[str, list[dict]], src: str, pulled: str) -> str:
    out = [
        'import type { ClusterActionItem } from "@/models/cluster";',
        "",
        "/**",
        " * Full open-action lists per pilot store — every alert sent in the last 7",
        " * days that is still unresolved (untouched, in progress, or reminder only).",
        f" * Generated by regen_cluster_fixtures.py from {src} ({pulled}) — all rows",
        " * real (ALERTS_HISTORY_V1 + ALERT_ACTION_STATUS state machine).",
        " */",
        "export const openActionsByStoreId: Record<",
        "  string,",
        "  { items: ClusterActionItem[]; total: number }",
        "> = {",
    ]
    for sid in pilots_by_name(d):
        rows = items[str(sid)]
        out.append(f'  "{sid}": {{')
        out.append(f"    total: {len(rows)},")
        out.append("    items: [")
        for r in rows:
            chip = CHIP.get(r["alert_type"], r["alert_type"])
            desc = f", desc: {s('In ' + title(r['section']))}" if r.get("section") else ""
            out.append(
                f'      {{ chip: {s(chip)}, chipTone: "alert", name: {s(r["issue"])}'
                f'{desc}, sent: {s(fmt_sent(r["sent_date"]))}, state: {s(r["state"])}'
                ', completedAt: "", by: "" },'
            )
        out.append("    ],")
        out.append("  },")
    out.append("};")
    out.append("")
    return "\n".join(out)


BUILD_PANEL = '''
export function buildStorePanel(row: ClusterStoreRow): PanelD {
  const d = storeDetails[row.storeId];
  const open = openActionsByStoreId[row.storeId];
  const wasteValue = d?.wasteValue;
  return {
    variant: "store",
    eyebrow: "Store, last 7 days",
    title: row.storeName,
    kpis: [
      { label: "OSA", value: row.osa, delta: `Cluster average ${clusterAverages.osa}` },
      {
        label: "Waste",
        value: wasteValue != null ? `£${Math.round(wasteValue)}` : "—",
        delta:
          d?.wasteRate != null
            ? `${d.wasteRate}% of markdowns (cluster ${clusterAverages.wasteRate})`
            : "No markdown data",
      },
      {
        label: "Prompted compliance",
        value: row.promptedCompliance,
        delta: `Cluster average ${clusterAverages.promptedCompliance}`,
      },
      {
        label: "Action compliance",
        value: row.actionCompliance,
        delta:
          row.inPilot && d
            ? `${d.actioned} of ${d.sent} actioned (${d.completed} completed${d.partial ? `, ${d.partial} partial` : ""})`
            : "Not in the Smart Action pilot",
      },
    ],
    deptRows: d?.deptRows ?? [],
    openActions: open?.items ?? d?.openActions ?? [],
    openActionTotal: open?.total ?? d?.openActionTotal,
  };
}
'''


def emit_store_fixture(d: dict, items: dict[str, list[dict]], src: str, pulled: str) -> str:
    names = d["store_names"]
    avgs = cluster_avgs(d)
    out = [
        'import type {',
        '  ClusterStoreDetail,',
        '  ClusterStoreRow,',
        '  PanelD,',
        '} from "@/models/cluster";',
        'import { openActionsByStoreId } from "./clusterOpenActionsFixture";',
        "",
        "/**",
        " * Store table + store panel fixture — generated by regen_cluster_fixtures.py",
        f" * from {src} ({pulled}).",
        " *",
        " * Store list = the Smart Action pilot stores (same ids as",
        " * ComplianceOptions.TrialStoreIds in the API).",
        " *",
        " * OSA/prompted-markdown: KPI_AVAILABILITY_LATEST_V1, latest run.",
        " * Action counts: ALERTS_HISTORY_V1 + ALERT_ACTION_STATUS, sent in last 7 days;",
        " * actioned = interacted (completed | partial | couldnt_complete |",
        " * in_progress | reminder_set). Waste: WASTAGE_V1 / MARKDOWN_LOG_V1.",
        " * Dept OSA: osca_details_json by_division breakdown (worst 3 shown).",
        " */",
        "",
        "export const clusterAverages = {",
        f'  osa: "{avgs["osa"]}",',
        f'  promptedCompliance: "{avgs["prompted"]}",',
        f'  wasteRate: "{avgs["waste"]}",',
        "};",
        "",
        "export const storeRows: ClusterStoreRow[] = [",
    ]
    for sid in pilots_by_name(d):
        k = d["kpi_latest"][str(sid)]
        st = stats_of(d, sid)
        out.append(
            f'  {{ storeId: "{sid}", storeName: {s(names[str(sid)])},'
            f' osa: "{float(k["tw_osa_pct"]):.1f}%",'
            f' promptedCompliance: "{float(k["prompted_markdown_pct"]):.1f}%",'
            f' openActions: {len(items[str(sid)])},'
            f' actionCompliance: "{st["compliance"]}", inPilot: true }},'
        )
    out += ["];", "", "export const storeDetails: Record<string, ClusterStoreDetail> = {"]
    for sid in pilots_by_name(d):
        w = d["waste"].get(str(sid), {})
        wv = round(float(w.get("waste_value") or 0))
        mq = float(w.get("md_qty") or 0)
        wr = float(w.get("waste_qty") or 0) / mq * 100 if mq else 0
        st = stats_of(d, sid)
        out.append(f'  "{sid}": {{')
        out.append(
            f'    wasteValue: {wv}, wasteRate: {wr:.2f}, sent: {st["sent"]},'
            f' actioned: {st["actioned"]}, completed: {st["completed"]}, partial: {st["partial"]},'
        )
        out.append("    deptRows: [")
        for name, pct in depts_of(d["kpi_latest"][str(sid)])[:3]:
            out.append(f'      {{ label: {s(name)}, value: "{pct:.1f}%", barPct: {pct} }},')
        out.append("    ],")
        out.append("  },")
    out.append("};")
    out.append(BUILD_PANEL)
    return "\n".join(out)


def emit_html_stores(d: dict, items: dict[str, list[dict]]) -> str:
    """The full `const STORES = [...]` block for the standalone HTML."""
    names = d["store_names"]
    lines = ["const STORES = ["]
    for sid in pilots_by_name(d):
        k = d["kpi_latest"][str(sid)]
        st = stats_of(d, sid)
        w = d["waste"].get(str(sid), {})
        wv = round(float(w.get("waste_value") or 0))
        mq = float(w.get("md_qty") or 0)
        wr = float(w.get("waste_qty") or 0) / mq * 100 if mq else 0
        depts = ",".join(f"[{s(n)},{p:.1f}]" for n, p in depts_of(k)[:3])
        rows = items[str(sid)]
        lines.append(
            f'  {{ id: "{sid}", name: {s(names[str(sid)])}, osa: "{float(k["tw_osa_pct"]):.1f}%",'
            f' prompted: "{float(k["prompted_markdown_pct"]):.1f}%", open: {len(rows)},'
            f' compliance: "{st["compliance"]}", pilot: true, wasteValue: {wv},'
            f' wasteRate: "{wr:.1f}", sent: {st["sent"]}, actioned: {st["actioned"]},'
            f' completed: {st["completed"]}, partial: {st["partial"]},'
            f' depts: [{depts}], actions: ['
        )
        for r in rows:
            chip = CHIP.get(r["alert_type"], r["alert_type"])
            desc = f", desc: {s('In ' + title(r['section']))}" if r.get("section") else ""
            lines.append(
                f'    {{ chip: {s(chip)}, name: {s(r["issue"])}'
                f'{desc}, sent: {s(fmt_sent(r["sent_date"]))}, state: {s(r["state"])} }},'
            )
        lines.append("  ] },")
    lines.append("];")
    return "\n".join(lines)


def splice_html(path: Path, d: dict, items: dict[str, list[dict]]) -> None:
    """Replace the STORES array and CLUSTER consts by index splice — never
    regex over the array body (nested brackets break non-greedy matches)."""
    html = path.read_text(encoding="utf-8")
    start = html.index("const STORES = [")
    end = html.index("\n];", start) + len("\n];")
    html = html[:start] + emit_html_stores(d, items) + html[end:]

    avgs = cluster_avgs(d)
    html, n = re.subn(
        r'const CLUSTER_OSA = "[^"]*", CLUSTER_PROMPTED = "[^"]*", CLUSTER_WASTE = "[^"]*";',
        f'const CLUSTER_OSA = "{avgs["osa"]}", CLUSTER_PROMPTED = "{avgs["prompted"]}", '
        f'CLUSTER_WASTE = "{avgs["waste"]}";',
        html,
    )
    assert n == 1, "CLUSTER consts line not found or ambiguous"
    path.write_text(html, encoding="utf-8")

    # Verify: every store's `open` equals its action-item count.
    for m in re.finditer(r'\{ id: "(\d+)".*?open: (\d+),.*?actions: \[(.*?)\n  \]', html, re.S):
        sid, openc, body = m.groups()
        n_items = len(re.findall(r"\{ chip:", body))
        assert n_items == int(openc), f"store {sid}: open={openc} but {n_items} items"
    print(f"  html: {len(d['pilot_store_ids'])} stores spliced, item counts verified")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--metrics", type=Path, default=None)
    ap.add_argument("--html", type=Path, default=None,
                    help="Also splice the STORES array into this standalone HTML file")
    args = ap.parse_args()

    metrics = args.metrics or latest_metrics(SCRIPTS_DIR / "out")
    d = json.loads(metrics.read_text(encoding="utf-8"))
    pulled = d.get("pulled_at", "")
    items = open_items(d)
    print(f"metrics: {metrics.name} (pulled {pulled})")
    print(f"  {len(d['pilot_store_ids'])} pilot stores, "
          f"{sum(len(v) for v in items.values())} open actions")

    (UI_DATA / "clusterOpenActionsFixture.ts").write_text(
        emit_open_actions(d, items, metrics.name, pulled), encoding="utf-8")
    print(f"  wrote {UI_DATA / 'clusterOpenActionsFixture.ts'}")

    (UI_DATA / "clusterStoreFixture.ts").write_text(
        emit_store_fixture(d, items, metrics.name, pulled), encoding="utf-8")
    print(f"  wrote {UI_DATA / 'clusterStoreFixture.ts'}")

    if args.html:
        splice_html(args.html, d, items)


if __name__ == "__main__":
    main()
